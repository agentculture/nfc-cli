import { describe, expect, it } from "vitest";
import { VERBS, coerceParams, formFields, getVerb } from "./verbs";

describe("verbs.json (generated by scripts/export-verbs.py from REGISTRY)", () => {
  it("lists all 15 registry verbs with their routes", () => {
    expect(VERBS).toHaveLength(15);
    expect(getVerb("ndef", "format").route).toBe("/api/ndef/format");
    expect(getVerb("ndef", "format").writes_trailers).toBe(true);
    expect(getVerb("tag", "write").trailer_flag).toBe("include_trailers");
  });

  it("gives only mutating verbs an apply property", () => {
    for (const v of VERBS) {
      expect("apply" in v.schema.properties).toBe(v.mutating);
    }
  });

  it("throws for an unknown verb", () => {
    expect(() => getVerb("tag", "explode")).toThrow(/unknown verb/);
  });
});

describe("formFields", () => {
  it("derives typed fields from the JSON schema and never exposes control flags", () => {
    const fields = formFields(getVerb("tag", "write"));
    const names = fields.map((f) => f.name);
    expect(names).toEqual(["block", "data", "key", "key_type", "keys_file", "wait"]);
    expect(fields.find((f) => f.name === "block")).toMatchObject({
      type: "integer",
      required: true,
      label: "Block",
    });
    expect(fields.find((f) => f.name === "key_type")).toMatchObject({ default: "A" });
  });

  it("honours only / omit", () => {
    expect(formFields(getVerb("tag", "read"), { only: ["block", "count"] }).map((f) => f.name)).toEqual(
      ["block", "count"],
    );
    expect(formFields(getVerb("tag", "read"), { omit: ["keys_file", "wait", "key", "key_type"] }).map((f) => f.name)).toEqual(
      ["block", "count"],
    );
  });
});

describe("coerceParams", () => {
  const fields = formFields(getVerb("tag", "write"));
  it("drops blanks and parses integers", () => {
    expect(coerceParams(fields, { block: "4", data: " 00ff ", key: "" })).toEqual({
      params: { block: 4, data: "00ff" },
      errors: {},
    });
  });
  it("reports a non-integer and a missing required field", () => {
    const { errors } = coerceParams(fields, { block: "four" });
    expect(errors.block).toMatch(/whole number/);
    expect(errors.data).toMatch(/required/);
  });
});
